import pg from 'pg';

const { Pool } = pg;
let pool;

export async function getDb() {
  if (pool) return pool;

  const configuredUrl = process.env.DATABASE_URL;
  if (!configuredUrl) {
    throw new Error('DATABASE_URL must be set to connect to PostgreSQL.');
  }

  const connectionUrl = new URL(configuredUrl);
  for (const option of ['sslmode', 'sslrootcert', 'sslcert', 'sslkey']) {
    connectionUrl.searchParams.delete(option);
  }

  const sslCa = process.env.DATABASE_SSL_CA?.replace(/\\n/g, '\n');

  pool = new Pool({
    connectionString: connectionUrl.toString(),
    max: 1,
    idleTimeoutMillis: 30000,
    connectionTimeoutMillis: 10000,
    ssl: process.env.DATABASE_SSL === 'disable'
      ? false
      : {
          rejectUnauthorized: Boolean(sslCa),
          ...(sslCa ? { ca: sslCa } : {}),
        },
  });

  pool.on('error', error => {
    console.error('Unexpected error from an idle PostgreSQL client:', error);
  });

  return pool;
}

export async function initializeDatabase() {
  const database = await getDb();

  await database.query(`
    CREATE TABLE IF NOT EXISTS services (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL UNIQUE,
      description TEXT NOT NULL,
      icon TEXT DEFAULT 'fa-tools',
      image TEXT,
      "order" INTEGER DEFAULT 0,
      is_active SMALLINT DEFAULT 1 CHECK (is_active IN (0, 1)),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS projects (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      description TEXT NOT NULL,
      image TEXT,
      status TEXT DEFAULT 'completed' CHECK (status IN ('completed', 'ongoing', 'upcoming')),
      location TEXT,
      year TEXT,
      is_featured SMALLINT DEFAULT 0 CHECK (is_featured IN (0, 1)),
      "order" INTEGER DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS team_members (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      role TEXT NOT NULL,
      bio TEXT,
      photo TEXT,
      email TEXT,
      phone TEXT,
      linkedin TEXT,
      "order" INTEGER DEFAULT 0,
      is_active SMALLINT DEFAULT 1 CHECK (is_active IN (0, 1)),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS testimonials (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      client_name TEXT NOT NULL,
      client_role TEXT,
      client_company TEXT,
      photo TEXT,
      message TEXT NOT NULL,
      rating INTEGER DEFAULT 5 CHECK (rating >= 1 AND rating <= 5),
      is_active SMALLINT DEFAULT 1 CHECK (is_active IN (0, 1)),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS machine_hires (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      description TEXT,
      image TEXT,
      rate TEXT,
      is_available SMALLINT DEFAULT 1 CHECK (is_available IN (0, 1)),
      "order" INTEGER DEFAULT 0,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS contact_messages (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL,
      phone TEXT,
      message TEXT NOT NULL,
      is_read SMALLINT DEFAULT 0 CHECK (is_read IN (0, 1)),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS consultation_bookings (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL,
      phone TEXT NOT NULL,
      service_interest TEXT,
      preferred_date DATE NOT NULL,
      preferred_time TIME NOT NULL,
      message TEXT,
      status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'cancelled', 'completed')),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE INDEX IF NOT EXISTS idx_services_active ON services(is_active);
    CREATE INDEX IF NOT EXISTS idx_projects_status ON projects(status);
    CREATE INDEX IF NOT EXISTS idx_projects_featured ON projects(is_featured);
    CREATE INDEX IF NOT EXISTS idx_team_active ON team_members(is_active);
    CREATE INDEX IF NOT EXISTS idx_testimonials_active ON testimonials(is_active);
    CREATE INDEX IF NOT EXISTS idx_machines_available ON machine_hires(is_available);
    CREATE INDEX IF NOT EXISTS idx_contact_read ON contact_messages(is_read);
    CREATE INDEX IF NOT EXISTS idx_bookings_status ON consultation_bookings(status);
  `);
}

export async function closeDb() {
  if (!pool) return;
  const database = pool;
  pool = undefined;
  await database.end();
}

export default { getDb, initializeDatabase, closeDb };
